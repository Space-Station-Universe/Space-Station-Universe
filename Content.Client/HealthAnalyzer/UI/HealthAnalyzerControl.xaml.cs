// Health analyzer UI is split from its window because it's used by both the
// health analyzer item and the cryo pod UI.
[GenerateTypedNameReferences]
public sealed partial class HealthAnalyzerControl : BoxContainer
{
    private readonly IResourceCache _cache;
    private readonly IEntityManager _entityManager;
    private readonly IPrototypeManager _prototypes;
    private readonly DamageableSystem _damageable;
    private readonly SpriteSystem _spriteSystem;

    // BEGIN SSU EDITS - Far Horizons limb damage
    private readonly LimbDamageSystem _limbDamage;
    private static readonly ProtoId<OrganCategoryPrototype> DefaultLimb = "Torso";
    private static readonly ProtoId<LimbTargettingPrototype> DefaultLimbVisuals = "LimbTargetHuman";
    private ProtoId<OrganCategoryPrototype> _currTarget = DefaultLimb;
    private EntityUid? _targetEnt;
    // END SSU EDITS

    public HealthAnalyzerControl()
    {
        RobustXamlLoader.Load(this);

        var dependencies = IoCManager.Instance!;
        _cache = dependencies.Resolve<IResourceCache>();
        _entityManager = dependencies.Resolve<IEntityManager>();
        _prototypes = dependencies.Resolve<IPrototypeManager>();
        _spriteSystem = _entityManager.System<SpriteSystem>();
        _damageable = _entityManager.System<DamageableSystem>();

        _limbDamage = _entityManager.System<LimbDamageSystem>(); // SSU: Far Horizons limb damage
        LimbTargettingDisplay.OnSelectedLimb += SetLimbTarget; // ditto
    }

    /// <summary>
    /// Populate the UI via a state.
    /// </summary>
    /// <param name="state">The state that carries the information about the patient.</param>
    public void Populate(HealthAnalyzerUiState state)
    {
        PopulateDataFields(state.TargetEntity, state.ScanMode, state.BloodLevel, state.Unrevivable, state.Bleeding);
        if (!float.IsNaN(state.Temperature))
            PopulateTemperature(state.Temperature);
    }

    /// <summary>
    /// Populates the UI directly.
    /// </summary>
    /// <param name="targetEntity">The entity being analyzed.</param>
    /// <param name="scanMode">The current scanmode of the analyzer.</param>
    /// <param name="bloodlevel">The bloodlevel of the entity.</param>
    /// <param name="unrevivable">Whether this entity is revivable.</param>
    /// <param name="bleeding">Whether this entity is bleeding.</param>
    private void PopulateDataFields(NetEntity? targetEntity, bool scanMode, float bloodlevel, bool unrevivable, bool bleeding)
    {
        var target = _entityManager.GetEntity(targetEntity);

        // If the entity has been deleted,
        if (_entityManager.Deleted(target))
        {
            // At the start, the health analyzer will have no entity. So we simply do nothing if it has never been used.
            if (NoPatientDataText.Visible)
                return;
            // If the target is still null even though it was used, that means the target has been deleted.
            ScanModeLabel.Text = Loc.GetString("health-analyzer-window-scan-mode-inactive");
            ScanModeLabel.FontColorOverride = Color.Red;
            SpriteView.Visible = false;
            LimbTargettingDisplay.Visible = false; // SSU: Far Horizons limb damage
            NoDataTex.Visible = true;
            return;
        }
        NoPatientDataText.Visible = false;

        // Scan Mode
        ScanModeLabel.Text = scanMode
            ? Loc.GetString("health-analyzer-window-scan-mode-active")
            : Loc.GetString("health-analyzer-window-scan-mode-inactive");

        ScanModeLabel.FontColorOverride = scanMode ? Color.Green : Color.Red;

        // Patient Information
        SpriteView.SetEntity(target.Value);
        SpriteView.Visible = scanMode;
        NoDataTex.Visible = !SpriteView.Visible;

        // BEGIN SSU EDITS - Far Horizons limb damage, show the limb doll instead of the sprite
        if (target != _targetEnt)
            _currTarget = DefaultLimb;
        _targetEnt = target;

        var hasLimbs = _entityManager.TryGetComponent<LimbDamageableComponent>(target.Value, out var limbDamageable);
        LimbTargettingDisplay.Visible = scanMode && hasLimbs;
        if (hasLimbs)
        {
            SpriteView.Visible = false;
            LimbTargettingDisplay.InitTarget(_prototypes, _cache, _spriteSystem,
                _prototypes.HasIndex(limbDamageable!.Proto) ? limbDamageable.Proto : DefaultLimbVisuals);
            LimbTargettingDisplay.UpdateLimb(_currTarget);
        }
        // END SSU EDITS

        var name = new FormattedMessage();
        name.PushColor(Color.White);
        name.AddText(_entityManager.HasComponent<MetaDataComponent>(target.Value)
            ? Identity.Name(target.Value, _entityManager)
            : Loc.GetString("health-analyzer-window-entity-unknown-text"));

        // If the scanned entity was changed, we need to reset the temperature label.
        if (name.ToMarkup() != NameLabel.Text)
            TemperatureLabel.Text = Loc.GetString("health-analyzer-window-entity-unknown-temperature-text");

        NameLabel.SetMessage(name);

        SpeciesLabel.Text =
            _entityManager.TryGetComponent<HumanoidProfileComponent>(target.Value,
                out var humanoidComponent)
                ? Loc.GetString(_prototypes.Index(humanoidComponent.Species).Name)
                : Loc.GetString("health-analyzer-window-entity-unknown-species-text");

        // Basic Diagnostic
        BloodLabel.Text = !float.IsNaN(bloodlevel)
            ? $"{bloodlevel * 100:F1} %"
            : Loc.GetString("health-analyzer-window-entity-unknown-value-text");

        StatusLabel.Text =
            _entityManager.TryGetComponent<MobStateComponent>(target.Value, out var mobStateComponent)
                ? GetStatus(mobStateComponent.CurrentState)
                : Loc.GetString("health-analyzer-window-entity-unknown-text");

        if (!_entityManager.HasComponent<DamageableComponent>(target.Value))
            return;

        // Total Damage
        DamageLabel.Text = _damageable.GetTotalDamage(target.Value).ToString();
        SetBodyLabelsVisible(true); // SSU: Far Horizons limb damage

        // Alerts
        var showAlerts = unrevivable || bleeding;

        AlertsDivider.Visible = showAlerts;
        AlertsContainer.Visible = showAlerts;

        if (showAlerts)
            AlertsContainer.RemoveAllChildren();

        if (unrevivable)
        {
            AlertsContainer.AddChild(new RichTextLabel
            {
                Text = Loc.GetString("health-analyzer-window-entity-unrevivable-text"),
                Margin = new Thickness(0, 4),
                MaxWidth = 300,
            });
        }
        if (bleeding)
        {
            AlertsContainer.AddChild(new RichTextLabel
            {
                Text = Loc.GetString("health-analyzer-window-entity-bleeding-text"),
                Margin = new Thickness(0, 4),
                MaxWidth = 300,
            });
        }

        // SSU: Far Horizons limb damage, per limb damage replaces the body totals below
        if (hasLimbs && Repopulate())
            return;

        // Damage Groups
        var damageSortedGroups =
            _damageable.GetDamagePerGroup(target.Value)
                .OrderByDescending(damage => damage.Value)
                .ToDictionary(x => x.Key, x => x.Value);

        var damagePerType = _damageable.GetAllDamage(target.Value).DamageDict;

        DrawDiagnosticGroups(damageSortedGroups, damagePerType);
    }

    /// <summary>
    /// Populate the temperature label.
    /// </summary>
    /// <remarks>
    /// This has been isolated in a method due to temperature not being predicted, while the rest is.
    /// </remarks>
    private void PopulateTemperature(float temperature)
    {
        TemperatureLabel.Text = !float.IsNaN(temperature)
            ? $"{temperature - Atmospherics.T0C:F1} °C ({temperature:F1} K)"
            : Loc.GetString("health-analyzer-window-entity-unknown-temperature-text");
    }

    private static string GetStatus(MobState mobState)
    {
        return mobState switch
        {
            MobState.Alive => Loc.GetString("health-analyzer-window-entity-alive-text"),
            MobState.Critical => Loc.GetString("health-analyzer-window-entity-critical-text"),
            MobState.Dead => Loc.GetString("health-analyzer-window-entity-dead-text"),
            _ => Loc.GetString("health-analyzer-window-entity-unknown-text"),
        };
    }

    private void DrawDiagnosticGroups(
        Dictionary<ProtoId<DamageGroupPrototype>, FixedPoint2> groups,
        IReadOnlyDictionary<ProtoId<DamageTypePrototype>, FixedPoint2> damageDict)
    {
        GroupsContainer.RemoveAllChildren();

        foreach (var (damageGroupId, damageAmount) in groups)
        {
            if (damageAmount == 0)
                continue;

            var groupTitleText = $"{Loc.GetString(
                "health-analyzer-window-damage-group-text",
                ("damageGroup", _prototypes.Index(damageGroupId).LocalizedName),
                ("amount", damageAmount)
            )}";

            var groupContainer = new BoxContainer
            {
                Align = AlignMode.Begin,
                Orientation = LayoutOrientation.Vertical,
            };

            groupContainer.AddChild(CreateDiagnosticGroupTitle(groupTitleText, damageGroupId));

            GroupsContainer.AddChild(groupContainer);

            // Show the damage for each type in that group.
            var group = _prototypes.Index(damageGroupId);

            foreach (var type in group.DamageTypes)
            {
                if (!damageDict.TryGetValue(type, out var typeAmount) || typeAmount <= 0)
                    continue;

                var damageString = Loc.GetString(
                    "health-analyzer-window-damage-type-text",
                    ("damageType", _prototypes.Index(type).LocalizedName),
                    ("amount", typeAmount)
                );

                groupContainer.AddChild(CreateDiagnosticItemLabel(damageString.Insert(0, " · ")));
            }
        }
    }

    // BEGIN SSU EDITS - Far Horizons limb damage
    private void SetLimbTarget(ProtoId<OrganCategoryPrototype> target)
    {
        _currTarget = target;
        LimbTargettingDisplay.UpdateLimb(_currTarget);
        Repopulate();
    }

    /// <summary>
    /// Shows the damage of the selected limb. Returns false if the target has no limb damage to show.
    /// </summary>
    private bool Repopulate()
    {
        if (_targetEnt == null || _entityManager.Deleted(_targetEnt))
            return false;

        var fullBodyDamage = _limbDamage.TryGetFullBodyDamage(_targetEnt.Value);
        var fullBodyDamageGroups = _limbDamage.TryGetFullBodyDamageGroups(_targetEnt.Value);

        if (fullBodyDamage == null || fullBodyDamageGroups == null)
            return false;

        if (!fullBodyDamage.ContainsKey(_currTarget))
        {
            _currTarget = DefaultLimb;
            LimbTargettingDisplay.UpdateLimb(_currTarget);
        }

        LimbTargettingDisplay.SetHealth(fullBodyDamage.ToDictionary(p => p.Key, p => p.Value.Sum(e => (float)e.Value)));

        DamageLabel.Text = fullBodyDamage[_currTarget].Select(p => (float)p.Value).Sum().ToString();

        var sortedGroups = fullBodyDamageGroups[_currTarget]
            .OrderByDescending(g => g.Value)
            .ToDictionary(g => g.Key, g => g.Value);

        DrawDiagnosticGroups(sortedGroups, fullBodyDamage[_currTarget]);

        SetBodyLabelsVisible(_currTarget == DefaultLimb);
        return true;
    }

    private void SetBodyLabelsVisible(bool visible)
    {
        StatusText.Visible = visible;
        StatusLabel.Visible = visible;
        TemperatureText.Visible = visible;
        TemperatureLabel.Visible = visible;
        BloodText.Visible = visible;
        BloodLabel.Visible = visible;
    }
    // END SSU EDITS

    private Texture GetTexture(string texture)
    {
        var rsiPath = new ResPath("/Textures/Objects/Devices/health_analyzer.rsi");
        var rsiSprite = new SpriteSpecifier.Rsi(rsiPath, texture);

        var rsi = _cache.GetResource<RSIResource>(rsiSprite.RsiPath).RSI;
        if (!rsi.TryGetState(rsiSprite.RsiState, out _))
        {
            rsiSprite = new SpriteSpecifier.Rsi(rsiPath, "unknown");
        }

        return _spriteSystem.Frame0(rsiSprite);
    }

    private static Label CreateDiagnosticItemLabel(string text)
    {
        return new Label
        {
            Text = text,
        };
    }

    private BoxContainer CreateDiagnosticGroupTitle(string text, string id)
    {
        var rootContainer = new BoxContainer
        {
            Margin = new Thickness(0, 6, 0, 0),
            VerticalAlignment = VAlignment.Bottom,
            Orientation = LayoutOrientation.Horizontal,
        };

        rootContainer.AddChild(new TextureRect
        {
            SetSize = new Vector2(30, 30),
            Texture = GetTexture(id.ToLower())
        });

        rootContainer.AddChild(CreateDiagnosticItemLabel(text));

        return rootContainer;
    }
}
